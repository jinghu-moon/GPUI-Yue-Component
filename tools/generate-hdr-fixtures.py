"""Generate tiny, original HDR fixtures using only Python's standard library.

No user photograph or third-party ICC profile is redistributed. The ST 2084
constants are exact rationals from BT.2100; JSON records the quantized samples,
not the unquantized labels. Re-run with --check to verify committed bytes.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import zlib


ROOT = Path(__file__).resolve().parents[1] / "crates/yue-component/tests/fixtures/hdr"
M1, M2 = 2610 / 16384, 2523 / 32
C1, C2, C3 = 3424 / 4096, 2413 / 128, 2392 / 128


def pq_encode(nits):
    p = (nits / 10000) ** M1
    return ((C1 + C2 * p) / (1 + C3 * p)) ** M2


def pq_decode(code):
    p = code ** (1 / M2)
    return 10000 * (max(p - C1, 0) / (C2 - C3 * p)) ** (1 / M1)


def map_nits(nits, source_peak, target_peak=100):
    if source_peak <= target_peak or nits <= 0:
        return max(nits, 0)
    black = pq_encode(0)
    scale = pq_encode(min(source_peak, 10000)) - black
    maximum = (pq_encode(target_peak) - black) / scale
    knee = min(max(1.5 * maximum - 0.5, 0), 1)
    value = min(max((pq_encode(min(nits, source_peak)) - black) / scale, 0), 1)
    if value > knee and knee < 1:
        t = (value - knee) / (1 - knee)
        value = (2*t**3 - 3*t*t + 1)*knee + (t**3 - 2*t*t + t)*(1-knee) + (-2*t**3 + 3*t*t)*maximum
    return pq_decode(value * scale + black)


def sdr_linear(rgb, peak):
    luminance = sum(a*b for a, b in zip(rgb, [0.2126, 0.7152, 0.0722]))
    if luminance <= 0:
        return [0, 0, 0]
    neutral = min(max(map_nits(luminance*80, max(peak, 100)) / 100, 0), 1)
    scaled = [v / luminance * neutral for v in rgb]
    chroma = 1
    for v in scaled:
        if v < 0:
            chroma = min(chroma, neutral/(neutral-v))
        elif v > 1:
            chroma = min(chroma, (1-neutral)/(v-neutral))
    return [min(max(neutral + (v-neutral)*max(chroma, 0), 0), 1) for v in scaled]


def mapping_vectors():
    # Quantize the inputs to the actual FP16 source representation. The double
    # precision oracle is independent of the Rust/F32/HLSL implementations.
    inputs = [[0, 0, 0], [1, 1, 1], [2.5375]*3, [12.5]*3, [125]*3,
              [3, 0.1, 0.1], [-0.1, 3, 1], [-0.25, 12.5, 2.5375]]
    output = "// Generated by tools/generate-hdr-fixtures.py; original MIT data.\n"
    output += "const SDR_MAPPING_VECTORS: &[([f64; 3], f64, [f64; 3])] = &[\n"
    for source in inputs:
        rgb = [struct.unpack('<e', struct.pack('<e', value))[0] for value in source]
        peak = max(rgb)*80
        mapped = list(map(float, sdr_linear(rgb, peak)))
        output += f"    ({rgb!r}, {peak!r}, {mapped!r}),\n"
    return (output + "];\n").encode()


def chunk(kind, data):
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))


def png(pixels, depth=16, cicp=None, icc=None):
    width, height = len(pixels), 1
    output = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, depth, 6, 0, 0, 0))
    if cicp is not None:
        output += chunk(b"cICP", bytes(cicp))
    if icc is not None:
        output += chunk(b"iCCP", b"Synthetic sRGB\0\0" + zlib.compress(icc))
    samples = bytes(v for p in pixels for v in p) if depth == 8 else b"".join(struct.pack(">4H", *p) for p in pixels)
    return output + chunk(b"IDAT", zlib.compress(b"\0" + samples)) + chunk(b"IEND", b"")


def synthetic_srgb_icc():
    # ICC v4 matrix/TRC display profile, D50-adapted sRGB colorants. The seven
    # parameter curve implements the exact sRGB EOTF, with identity alpha.
    def fixed(x):
        return struct.pack(">i", round(x * 65536))

    def xyz(values):
        return b"XYZ \0\0\0\0" + b"".join(fixed(x) for x in values)

    curve = b"para\0\0\0\0" + struct.pack(">HH", 4, 0)
    curve += b"".join(fixed(x) for x in [2.4, 1 / 1.055, 0.055 / 1.055, 1 / 12.92, 0.04045, 0, 0])
    tags = [
        (b"wtpt", xyz([0.9642, 1, 0.8249])),
        (b"rXYZ", xyz([0.4360747, 0.2225045, 0.0139322])),
        (b"gXYZ", xyz([0.3850649, 0.7168786, 0.0971045])),
        (b"bXYZ", xyz([0.1430804, 0.0606169, 0.7141733])),
        (b"rTRC", curve), (b"gTRC", curve), (b"bTRC", curve),
    ]
    header = bytearray(128)
    header[8:12] = bytes([4, 0x30, 0, 0])
    header[12:24] = b"mntrRGB XYZ "
    header[24:36] = struct.pack(">6H", 2026, 11, 3, 0, 0, 0)
    header[36:40] = b"acsp"
    header[68:80] = b"".join(fixed(x) for x in [0.9642, 1, 0.8249])
    offset = 128 + 4 + 12 * len(tags)
    directory, body = b"", b""
    for name, payload in tags:
        directory += name + struct.pack(">II", offset, len(payload))
        padded = payload + b"\0" * (-len(payload) % 4)
        body += padded
        offset += len(padded)
    struct.pack_into(">I", header, 0, offset)
    return bytes(header) + struct.pack(">I", len(tags)) + directory + body


def generate():
    icc = synthetic_srgb_icc()
    labels = [0, 80, 100, 203, 1000, 10000]
    codes = [round(pq_encode(n) * 65535) for n in labels]
    gray = [(c, c, c, 65535) for c in codes]
    srgb = [(0x1000, 0x1000, 0x1000, 65535), (0x1010, 0x1010, 0x1010, 65535)]
    output = {
        "pq-gray.png": png(gray, cicp=[9, 16, 0, 1]),
        "pq-alpha.png": png([(65535, 0, 0, 0), (0, 0, codes[4], 65535)], cicp=[9, 16, 0, 1]),
        "srgb16-gray.png": png(srgb, cicp=[1, 13, 0, 1]),
        "icc-srgb16.png": png(srgb, icc=icc),
        "cicp-over-icc.png": png(gray, cicp=[9, 16, 0, 1], icc=icc),
        "unsupported-hlg.png": png(gray, cicp=[9, 18, 0, 1]),
        "invalid-matrix.png": png(gray, cicp=[9, 16, 1, 1]),
        "srgb-matrix.icc": icc,
        "sdr-vectors.rs": mapping_vectors(),
    }
    manifest = {
        "generator": "tools/generate-hdr-fixtures.py",
        "license": "MIT (original synthetic data; project LICENSE)",
        "pq": [{"label_nits": n, "code_u16": c, "decoded_nits": pq_decode(c / 65535)} for n, c in zip(labels, codes)],
        "files": [{"name": n, "bytes": len(b), "sha256": hashlib.sha256(b).hexdigest()} for n, b in sorted(output.items())],
    }
    output["manifest.json"] = (json.dumps(manifest, indent=2) + "\n").encode()
    return output


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        bad = [name for name, data in generated.items() if not (ROOT / name).exists() or (ROOT / name).read_bytes() != data]
        if bad:
            raise SystemExit("HDR fixtures differ: " + ", ".join(bad))
    else:
        ROOT.mkdir(parents=True, exist_ok=True)
        for name, data in generated.items():
            (ROOT / name).write_bytes(data)
    print(f"HDR fixtures {'verified' if args.check else 'generated'}: {len(generated)} files")
